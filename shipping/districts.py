# Legacy alias mappings for backward compatibility
DISTRICT_ALIASES = {
    'Chittagong': 'Chattogram',
    'Bogra': 'Bogura',
    'Jessore': 'Jashore',
    'Comilla': 'Cumilla',
    'Barisal': 'Barishal',
    'Netrakona': 'Netrokona',
}

def normalize_district(name):
    """Normalize district name to standard key if alias exists."""
    if not name:
        return 'Dhaka'
    cleaned = str(name).strip()
    return DISTRICT_ALIASES.get(cleaned, cleaned)
